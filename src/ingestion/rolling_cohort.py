"""Safe local Rolling Cohort prototype (T0 and T+24h) for the YouTube project.

Reads candidate JSON generated by src.ingestion.discover_playlist_videos.
Does NOT update the master CSV, SQL Server or MinIO. Those are separate integration steps.

From project root:
  uv run python -m src.ingestion.rolling_cohort inspect --region VN --candidates data/raw/playlist_discovery/VN/playlist_candidates_VN_20261012_145639.json --limit 10
  uv run python -m src.ingestion.rolling_cohort start --region VN --candidates data/raw/playlist_discovery/VN/playlist_candidates_VN_20261012_145639.json --limit 10
  uv run python -m src.ingestion.rolling_cohort status --region VN
  uv run python -m src.ingestion.rolling_cohort update --manifest data/raw/rolling_cohorts/VN/<batch_id>/manifest.json

'update' refuses to run before 24 hours (unless a test fixture changes the time).
"""

import argparse
import json
import math
import os
import tempfile
from datetime import datetime, timedelta, timezone
from pathlib import Path

import pandas as pd
from dotenv import load_dotenv

from src.ingestion.discover_playlist_videos import YouTubeClient

load_dotenv()

DEFAULT_MASTER = Path('data/processed/youtube_dataset_2000_clean.csv')
COHORT_ROOT = Path('data/raw/rolling_cohorts')
OUTPUT_ROOT = Path('data/processed')
REGIONS = ('VN', 'US', 'JP')


def now_utc():
    return datetime.now(timezone.utc)


def parse_dt(value):
    return datetime.fromisoformat(str(value).replace('Z', '+00:00')).astimezone(timezone.utc)


def save_json_atomic(path, payload):
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile(mode='w', encoding='utf-8', dir=path.parent,
                                     prefix='.temp_', suffix='.json', delete=False) as f:
        temp_name = f.name
        json.dump(payload, f, ensure_ascii=False, indent=2)
    os.replace(temp_name, path)


def load_json(path):
    return json.loads(path.read_text(encoding='utf-8-sig'))


def known_video_ids(master_path, cohort_root):
    if not master_path.is_file():
        raise FileNotFoundError(f'Master dataset not found: {master_path}')
    df = pd.read_csv(master_path, usecols=['video_id'], dtype={'video_id': 'string'})
    ids = set(df['video_id'].dropna().astype(str))
    previous = 0
    if cohort_root.exists():
        for p in cohort_root.glob('*/**/t0.json'):
            payload = load_json(p)
            for item in payload.get('records', []):
                ids.add(str(item['video_id']))
                previous += 1
    return ids, previous


def candidate_rows(input_path, region, known_ids, limit):
    payload = load_json(input_path)
    if payload.get('region_seed') != region:
        raise ValueError(f'Region mismatch: candidate file is for {payload.get("region_seed")}, requested {region}')
    rows = payload.get('candidates')
    if not isinstance(rows, list):
        raise ValueError('Candidate JSON must contain a candidates array')
    selected = []
    seen = set()
    for item in rows:
        video_id = str(item.get('video_id', '')).strip()
        if not video_id or video_id in known_ids or video_id in seen:
            continue
        seen.add(video_id)
        selected.append(item)
        if len(selected) >= limit:
            break
    return selected, len(rows)


def details_by_id(client, ids):
    result = {}
    for i in range(0, len(ids), 50):
        data = client.get('videos', part='snippet,statistics,contentDetails',
                          id=','.join(ids[i:i + 50]), maxResults=50)
        fetched_at = now_utc().isoformat()
        for item in data.get('items', []):
            result[item['id']] = (item, fetched_at)
    return result


def int_or_none(value):
    try:
        return int(value) if value is not None and value != '' else None
    except (ValueError, TypeError):
        return None


def region_availability(item, region):
    restriction = item.get('contentDetails', {}).get('regionRestriction', {})
    allowed = restriction.get('allowed')
    blocked = restriction.get('blocked')
    if isinstance(allowed, list):
        return 'allowed' if region in allowed else 'blocked'
    if isinstance(blocked, list):
        return 'blocked' if region in blocked else 'not_blocked'
    return 'not_specified'


def command_inspect(args):
    known, previous = known_video_ids(args.master_path, args.output_root)
    selected, raw_count = candidate_rows(args.candidates, args.region, known, args.limit)
    print('Mode: INSPECT (no API requests, no files modified)')
    print('Region seed:', args.region)
    print('Candidates in input:', raw_count)
    print('Tracked in previous cohorts:', previous)
    print('New candidates selected:', len(selected))
    print('Expected videos.list requests:', math.ceil(len(selected) / 50))
    print('First video IDs:', ', '.join(x['video_id'] for x in selected[:10]))


def command_start(args):
    known, previous = known_video_ids(args.master_path, args.output_root)
    selected, raw_count = candidate_rows(args.candidates, args.region, known, args.limit)
    if not selected:
        print('No new candidates. Nothing written.')
        return
    required_calls = math.ceil(len(selected) / 50)
    if required_calls > args.max_requests:
        raise SystemExit(f'Need {required_calls} videos.list requests, exceeds --max-requests {args.max_requests}')
    key = os.getenv('YOUTUBE_API_KEY')
    if not key:
        raise SystemExit('YOUTUBE_API_KEY not found in .env')
    client = YouTubeClient(key, args.max_requests)
    try:
        fetched = details_by_id(client, [x['video_id'] for x in selected])
    finally:
        client.session.close()
    batch_time = now_utc()
    batch_id = f'{args.region}_{batch_time.strftime("%Y%m%d_%H%M%S_%f")}'
    out_dir = args.output_root / args.region / batch_id
    if out_dir.exists():
        raise FileExistsError(f'Batch directory already exists: {out_dir}')
    records = []
    for source in selected:
        vid = source['video_id']
        if vid not in fetched:
            continue  # private / deleted / not returned by videos.list
        item, fetched_at = fetched[vid]
        snippet = item.get('snippet', {})
        stats = item.get('statistics', {})
        records.append({
            'video_id': vid,
            'region_code': args.region,
            'discovery_source': source.get('discovery_source', 'uploads_playlist'),
            'seed_channel_id': source.get('channel_id'),
            'seed_region': args.region,
            'discovery_batch_id': batch_id,
            'first_seen_at': fetched_at,
            'collected_at': fetched_at,
            'title': snippet.get('title'),
            'channel_id': snippet.get('channelId'),
            'channel_title': snippet.get('channelTitle'),
            'category_id': snippet.get('categoryId'),
            'published_at': snippet.get('publishedAt'),
            'view_count': int_or_none(stats.get('viewCount')),
            'like_count': int_or_none(stats.get('likeCount')),
            'comment_count': int_or_none(stats.get('commentCount')),
            'region_availability': region_availability(item, args.region),
        })
    if not records:
        print('API did not return details for any candidate. Nothing written.')
        return
    latest = max(parse_dt(r['collected_at']) for r in records)
    due_at = latest + timedelta(hours=24)
    manifest = {
        'schema_version': 1,
        'batch_id': batch_id,
        'region_code': args.region,
        'source_candidates_file': str(args.candidates),
        'status': 'PENDING_T24',
        'created_at_utc': batch_time.isoformat(),
        'due_at_utc': due_at.isoformat(),
        'candidates_input_count': raw_count,
        'candidates_selected': len(selected),
        'video_ids_confirmed': len(records),
        'api_calls': client.request_count,
        't0_path': str(out_dir / 't0.json'),
        't24_path': str(out_dir / 't24.json'),
    }
    save_json_atomic(out_dir / 't0.json', {'batch_id': batch_id, 'region_code': args.region, 'records': records})
    save_json_atomic(out_dir / 'manifest.json', manifest)
    print('T0 SAVED (local only; master/SQL/MinIO unchanged)')
    print('Selected:', len(selected), '| Confirmed:', len(records), '| API calls:', client.request_count)
    print('Manifest:', out_dir / 'manifest.json')
    print('Due T+24h (UTC):', due_at.isoformat())
    print('Note: seed_region does not establish creator nationality or chart eligibility.')


def command_status(args):
    root = args.output_root / args.region
    if not root.exists():
        print('No Rolling Cohort batches for', args.region)
        return
    paths = sorted(root.glob('*/manifest.json'))
    print(f'{args.region} batches:', len(paths))
    for path in paths[-20:]:
        m = load_json(path)
        print(f"{m.get('batch_id')} | {m.get('status')} | {m.get('video_ids_confirmed')} videos | due {m.get('due_at_utc')}")


def command_update(args):
    manifest_path = args.manifest
    manifest = load_json(manifest_path)
    if manifest.get('status') == 'COMPLETED':
        print('Batch already completed. No API request and no duplicate output.')
        return
    if manifest.get('status') != 'PENDING_T24':
        raise SystemExit(f"Unexpected batch status: {manifest.get('status')}")
    t0_path = manifest_path.parent / 't0.json'
    t24_path = manifest_path.parent / 't24.json'
    if t24_path.exists():
        raise SystemExit('t24.json already exists but manifest is not COMPLETED. Investigate before retrying.')
    t0 = load_json(t0_path)
    rows = t0.get('records', [])
    if not rows:
        raise SystemExit('T0 records are missing')
    due = parse_dt(manifest['due_at_utc'])
    if now_utc() < due:
        raise SystemExit(f'Batch not due yet. Earliest scheduled T+24h: {due.isoformat()}')
    required = math.ceil(len(rows) / 50)
    if required > args.max_requests:
        raise SystemExit(f'Need {required} videos.list requests, exceeds --max-requests {args.max_requests}')
    key = os.getenv('YOUTUBE_API_KEY')
    if not key:
        raise SystemExit('YOUTUBE_API_KEY not found in .env')
    client = YouTubeClient(key, args.max_requests)
    try:
        fetched = details_by_id(client, [r['video_id'] for r in rows])
    finally:
        client.session.close()
    final_rows = []
    for prev in rows:
        item, collected_at = fetched.get(prev['video_id'], (None, now_utc().isoformat()))
        st = item.get('statistics', {}) if item is not None else {}
        new_views = int_or_none(st.get('viewCount'))
        new_likes = int_or_none(st.get('likeCount'))
        new_comments = int_or_none(st.get('commentCount'))
        hrs = (parse_dt(collected_at) - parse_dt(prev['collected_at'])).total_seconds() / 3600
        delta = None if new_views is None or prev['view_count'] is None else new_views - prev['view_count']
        final_rows.append({
            **prev,
            't0_collected_at': prev['collected_at'],
            't24_collected_at': collected_at,
            't24_video_available': item is not None,
            't24_view_count': new_views,
            't24_like_count': new_likes,
            't24_comment_count': new_comments,
            'hours_elapsed': round(hrs, 5),
            'view_delta_24h': delta,
            'views_per_hour_avg_24h': None if delta is None or hrs <= 0 else round(delta / hrs, 3),
            'like_delta_24h': None if new_likes is None or prev['like_count'] is None else new_likes - prev['like_count'],
            'comment_delta_24h': None if new_comments is None or prev['comment_count'] is None else new_comments - prev['comment_count'],
        })
    save_json_atomic(t24_path, {'batch_id': manifest['batch_id'], 'region_code': manifest['region_code'], 'records': final_rows})
    manifest['status'] = 'COMPLETED'
    manifest['completed_at_utc'] = now_utc().isoformat()
    manifest['api_calls_update'] = client.request_count
    save_json_atomic(manifest_path, manifest)
    print('T+24h SAVED (local only; master/SQL/MinIO unchanged)')
    print('Videos:', len(final_rows), '| API calls:', client.request_count)
    print('Output:', t24_path)


def main():
    parser = argparse.ArgumentParser(description='Rolling Cohort local T0/T+24h prototype (no SQL/MinIO/master writes).')
    sub = parser.add_subparsers(dest='command', required=True)
    for cmd in ('inspect', 'start'):
        p = sub.add_parser(cmd)
        p.add_argument('--region', choices=REGIONS, required=True)
        p.add_argument('--candidates', type=Path, required=True)
        p.add_argument('--limit', type=int, default=10)
        p.add_argument('--master-path', type=Path, default=DEFAULT_MASTER)
        p.add_argument('--output-root', type=Path, default=COHORT_ROOT)
        if cmd == 'start':
            p.add_argument('--max-requests', type=int, default=4)
    s = sub.add_parser('status')
    s.add_argument('--region', choices=REGIONS, required=True)
    s.add_argument('--output-root', type=Path, default=COHORT_ROOT)
    u = sub.add_parser('update')
    u.add_argument('--manifest', type=Path, required=True)
    u.add_argument('--max-requests', type=int, default=200)
    args = parser.parse_args()
    if hasattr(args, 'limit') and args.limit <= 0:
        parser.error('--limit must be positive')
    if hasattr(args, 'max_requests') and args.max_requests <= 0:
        parser.error('--max-requests must be positive')
    if args.command == 'inspect':
        command_inspect(args)
    elif args.command == 'start':
        command_start(args)
    elif args.command == 'status':
        command_status(args)
    elif args.command == 'update':
        command_update(args)


if __name__ == '__main__':
    main()
